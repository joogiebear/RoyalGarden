package com.mystipixel.royalgarden.garden;

import com.mystipixel.royalgarden.config.Durations;
import com.mystipixel.royalgarden.config.GardenConfig;
import com.mystipixel.royalgarden.config.Messages;
import com.mystipixel.royalgarden.config.YamlFile;
import com.mystipixel.royalskyblock.currency.Cost;
import org.bukkit.Material;
import org.bukkit.configuration.ConfigurationSection;
import org.bukkit.configuration.InvalidConfigurationException;
import org.bukkit.configuration.file.YamlConfiguration;

import java.io.File;
import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.logging.Logger;

/**
 * Plot presets. Templates are captured blocks, one {@code .preset} file each under {@code presets/},
 * read on first use and cached. The catalogue, {@code presets.yml}, says which players may pick at the
 * desk and on what terms, and holds {@code default:} for new Gardens. {@code flat} and {@code bedrock}
 * are generated, need no file and cannot be deleted.
 */
public final class PresetLibrary {

    // Ids are file names, so they are restricted to something that cannot escape the directory.
    private static final String ID_PATTERN = "[a-z0-9_-]{1,32}";

    /** One preset as players see it at the desk. */
    public record Entry(String id, String displayName, Material icon, List<String> lore, Cost cost,
                        long cooldownMillis, String permission, boolean selectable, int gardenLevel) {
    }

    private final File dir;
    private final YamlFile index;
    private final Logger logger;
    private final Messages messages;
    private final Map<String, PlotTemplate> cache = new HashMap<>();

    public PresetLibrary(File dataFolder, Messages messages, Logger logger) {
        this.dir = new File(dataFolder, "presets");
        this.logger = logger;
        this.messages = messages;
        if (!dir.exists() && !dir.mkdirs()) {
            logger.warning("Could not create " + dir + "; plot presets will not persist.");
        }
        boolean fresh = !new File(dataFolder, "presets.yml").exists();
        this.index = new YamlFile(dataFolder, "presets.yml", logger, false);
        if (fresh) {
            extractBundled();
        }
        checkDefault();
    }

    // Shipped in the jar and listed in the shipped presets.yml. Generated by tools/gen_presets.py.
    static final List<String> BUNDLED = List.of("wheat", "carrot", "potato", "sugar-cane", "nether-wart",
            "mushroom", "melon", "pumpkin");

    // First install only, so a preset an admin deleted never comes back. They are 96 wide, so on a board
    // with another plot size they stay in the jar.
    private void extractBundled() {
        if (GardenLayout.plotSize() != 96) {
            logger.info("Not writing the bundled presets: they are for 96-block plots, and plots are "
                    + GardenLayout.plotSize() + ". Remove their entries from presets.yml.");
            return;
        }
        for (String id : BUNDLED) {
            File target = fileFor(id);
            if (target.exists()) {
                continue;
            }
            try (InputStream in = PresetLibrary.class.getClassLoader()
                    .getResourceAsStream("royalgarden/presets/" + id + ".preset")) {
                if (in != null) {
                    Files.copy(in, target.toPath());
                }
            } catch (IOException failed) {
                logger.warning("Could not write the bundled preset '" + id + "': " + failed.getMessage());
            }
        }
    }

    /** Also drops cached templates so recaptured files are picked up. */
    public void reload() {
        index.reload();
        cache.clear();
        checkDefault();
    }

    private void checkDefault() {
        String id = defaultId();
        if (id != null && !exists(id)) {
            logger.warning("Default preset '" + id + "' is missing; new plots will be flat.");
        }
    }

    /**
     * Refuses {@code flat} and {@code bedrock}: a captured preset with one of those names would shadow a
     * state a plot must always be able to return to.
     */
    public static boolean validId(String id) {
        if (id == null) {
            return false;
        }
        String lower = id.toLowerCase(Locale.ROOT);
        return lower.matches(ID_PATTERN) && !GardenWorlds.isBuiltIn(lower);
    }

    private File fileFor(String id) {
        return new File(dir, id + ".preset");
    }

    public boolean exists(String id) {
        return validId(id) && fileFor(id).isFile();
    }

    /** A captured preset on disk, or one of the two built-ins. */
    public boolean applicable(String id) {
        return GardenWorlds.isBuiltIn(id) || exists(id);
    }

    /** Alphabetical. */
    public List<String> ids() {
        List<String> out = new ArrayList<>();
        File[] files = dir.listFiles((d, name) -> name.endsWith(".preset"));
        if (files != null) {
            for (File file : files) {
                String id = file.getName().substring(0, file.getName().length() - ".preset".length());
                if (validId(id)) {
                    out.add(id);
                }
            }
        }
        out.sort(String::compareTo);
        return out;
    }

    /** Null if missing or unreadable; an unreadable preset is logged, and the caller falls back to flat. */
    public PlotTemplate get(String id) {
        if (!validId(id)) {
            return null;
        }
        PlotTemplate cached = cache.get(id);
        if (cached != null) {
            return cached;
        }
        try {
            PlotTemplate loaded = PlotTemplate.load(fileFor(id));
            if (loaded != null) {
                cache.put(id, loaded);
            }
            return loaded;
        } catch (IOException bad) {
            logger.severe("Preset '" + id + "' could not be read: " + bad.getMessage());
            return null;
        }
    }

    /**
     * Replaces any preset already there. A first capture also adds a {@code selectable: false} catalogue
     * entry, ready to be named, priced and switched on.
     */
    public void save(String id, PlotTemplate preset) throws IOException {
        if (!validId(id)) {
            throw new IOException("'" + id + "' is not a valid preset name (a-z, 0-9, _ and - only).");
        }
        preset.save(fileFor(id));
        cache.put(id, preset);
        if (!index.yaml().isSet("presets." + id)) {
            editIndex(yaml -> {
                String path = "presets." + id;
                yaml.set(path + ".display-name", messages.raw("captured-preset-name", "%preset%", id));
                yaml.set(path + ".icon", "wheat");
                yaml.set(path + ".lore", messages.yaml().getStringList("captured-preset-lore"));
                yaml.set(path + ".cost", "0 coins");
                yaml.set(path + ".selectable", false);
            });
        }
    }

    /** Clears the default if that is what it was. */
    public boolean delete(String id) {
        if (!exists(id)) {
            return false;
        }
        cache.remove(id);
        boolean deleted = fileFor(id).delete();
        if (deleted && id.equals(defaultId())) {
            setDefault(null);
        }
        return deleted;
    }

    /** Null for a flat field. */
    public String defaultId() {
        String id = index.yaml().getString("default", "");
        return id == null || id.isBlank() || GardenWorlds.isBuiltIn(id) ? null : id.toLowerCase(Locale.ROOT);
    }

    public PlotTemplate defaultPreset() {
        String id = defaultId();
        return id == null ? null : get(id);
    }

    /** Null clears it. */
    public void setDefault(String id) {
        editIndex(yaml -> yaml.set("default", id == null ? "" : id));
    }

    /** Null if the id is not in {@code presets.yml}. */
    public Entry entry(String id) {
        if (id == null) {
            return null;
        }
        ConfigurationSection section = index.yaml().getConfigurationSection("presets." + id.toLowerCase(Locale.ROOT));
        if (section == null) {
            return null;
        }
        Material icon = Material.matchMaterial(section.getString("icon", "wheat"));
        String cooldown = section.getString("cooldown");
        return new Entry(
                id.toLowerCase(Locale.ROOT),
                section.getString("display-name", id),
                icon == null || !icon.isItem() ? Material.WHEAT : icon,
                section.getStringList("lore"),
                GardenConfig.parseCost(section, "cost", logger),
                cooldown == null ? -1L : Durations.parseMillis(cooldown),
                section.getString("permission", ""),
                section.getBoolean("selectable", true),
                Math.max(0, section.getInt("garden-level", 0)));
    }

    /** In the order {@code presets.yml} lists them. */
    public List<Entry> selectable() {
        List<Entry> out = new ArrayList<>();
        ConfigurationSection section = index.yaml().getConfigurationSection("presets");
        if (section == null) {
            return out;
        }
        for (String id : section.getKeys(false)) {
            Entry entry = entry(id);
            if (entry == null || !entry.selectable()) {
                continue;
            }
            if (!applicable(entry.id())) {
                logger.warning("presets.yml lists '" + id + "', but no such preset has been captured. "
                        + "Capture it with /garden capture " + id + ", or remove the entry.");
                continue;
            }
            out.add(entry);
        }
        return out;
    }

    private interface Edit {
        void apply(YamlConfiguration yaml);
    }

    // Read without the shipped defaults so writing back does not bake in every example entry, and refuse
    // to write if the file does not parse rather than replace the admin's catalogue.
    private void editIndex(Edit edit) {
        YamlConfiguration raw = new YamlConfiguration();
        File file = index.file();
        if (file.exists()) {
            try {
                raw.load(file);
            } catch (IOException | InvalidConfigurationException broken) {
                logger.severe("presets.yml does not parse, so it was not changed: " + broken.getMessage());
                return;
            }
        }
        edit.apply(raw);
        try {
            GardenStore.writeAtomically(file.toPath(), raw.saveToString());
        } catch (IOException e) {
            logger.severe("Could not save presets.yml: " + e.getMessage());
        }
        index.reload();
    }
}
